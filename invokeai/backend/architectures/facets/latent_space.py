def sample_to_lowres_estimated_image(
    samples: torch.Tensor,
    latent_rgb_factors: torch.Tensor,
    smooth_matrix: torch.Tensor | None = None,
    latent_rgb_bias: torch.Tensor | None = None,
) -> Image.Image:
    if samples.dim() == 4:
        samples = samples[0]
    latent_image = samples.permute(1, 2, 0) @ latent_rgb_factors

    if latent_rgb_bias is not None:
        latent_image = latent_image + latent_rgb_bias

    if smooth_matrix is not None:
        latent_image = latent_image.unsqueeze(0).permute(3, 0, 1, 2)
        latent_image = torch.nn.functional.conv2d(latent_image, smooth_matrix.reshape((1, 1, 3, 3)), padding=1)
        latent_image = latent_image.permute(1, 2, 3, 0).squeeze(0)

    latents_ubyte = (
        ((latent_image + 1) / 2).clamp(0, 1).mul(0xFF).byte()  # change scale from -1..1 to 0..1  # to 0..255
    ).cpu()

    return Image.fromarray(latents_ubyte.numpy())


@dataclass(frozen=True)
class LatentSpace:
    """One VAE latent geometry, and the linear projection that turns it into a preview image."""

    name: str
    """Stable identifier. Used in diagnostics and to keep the closed set closed in tests."""

    channels: int
    """Latent channel count. Also how `LatentSpaceFacet` tells its latent spaces apart at runtime."""

    spatial_compression: int
    """Image pixels per latent pixel, per axis. 8 everywhere except Wan's Wan2.2-VAE."""

    rgb_factors: list[list[float]]
    """A `channels` x 3 linear projection from latent space to RGB."""

    rgb_bias: list[float] | None = None
    smooth_matrix: list[list[float]] | None = None

    def __post_init__(self) -> None:
        if len(self.rgb_factors) != self.channels:
            raise ValueError(
                f"{self.name}: declares {self.channels} channels but carries {len(self.rgb_factors)} rgb_factors rows."
            )

    def preview(self, sample: torch.Tensor) -> Image.Image:
        """Project `sample` to a preview image at *latent* resolution.

        The caller scales the result by `spatial_compression` to get the image-space size. Keeping
        this a method rather than a bare factor matrix means an architecture that eventually needs a
        real tiny-VAE decode is not forced through a linear projection.
        """
        return sample_to_lowres_estimated_image(
            samples=sample,
            latent_rgb_factors=torch.tensor(self.rgb_factors, dtype=sample.dtype, device=sample.device),
            smooth_matrix=(
                torch.tensor(self.smooth_matrix, dtype=sample.dtype, device=sample.device)
                if self.smooth_matrix
                else None
            ),
            latent_rgb_bias=(
                torch.tensor(self.rgb_bias, dtype=sample.dtype, device=sample.device) if self.rgb_bias else None
            ),
        )


