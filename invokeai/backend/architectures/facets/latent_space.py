"""The VAE latent geometry of an architecture, and how to project it to a preview image.

The preview chain was never really keyed on architecture -- the branch comments in the dispatch
chain this replaces said so by hand ("Krea-2 decodes with the Qwen-Image VAE", "Z-Image uses
FLUX-compatible VAE", "Anima uses Wan 2.1 VAE"). Fifteen architectures share eight latent spaces,
and the five most recent ones introduced no new preview data at all.

Not migrated here, deliberately:

- `constants.LATENT_SCALE_FACTOR` (a module-level `8` with a live `HACK:` comment): its blast radius
  is every latent node. A follow-up, now that a correct source exists.
- `pid/decode.py`'s `_PER_BACKBONE`: same shape, different units. It describes packed latents
  (Flux2: 128 channels at 16x) where this describes VAE latents (Flux2: 32 channels at 8x). They
  are not derivable from one another.
"""

