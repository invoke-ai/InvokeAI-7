@dataclass(frozen=True)
class LatentSpaceFacet(Facet):
    """The latent space, or spaces, an architecture denoises in."""

    REQUIRED = True

    default: LatentSpace

    alternates: tuple[LatentSpace, ...] = ()
    """Further latent spaces this architecture may denoise in, told apart at runtime by the sample's
    channel count. Only Wan has any: A14B uses the 16-channel Wan 2.1 VAE, TI2V-5B the 48-channel
    Wan2.2-VAE, and before the registry the code picked between them by hand -- in two places, once
    for the factors and once for the spatial scale, which is exactly how those two could drift."""

    def __post_init__(self) -> None:
        channels = [latent_space.channels for latent_space in (self.default, *self.alternates)]
        if len(set(channels)) != len(channels):
            raise ValueError(
                f"{self.default.name}: latent spaces are selected by channel count, so no two may share one "
                f"(got {channels})."
            )

    def resolve(self, sample: torch.Tensor) -> LatentSpace:
        """The latent space matching `sample`'s channel count.

        An architecture with a single latent space returns it without inspecting the sample at all.
        That preserves the pre-registry behaviour: only the Wan branch ever read `sample.shape[-3]`,
        so an unusually shaped sample must not start raising IndexError for the other fourteen.
        """
        if not self.alternates:
            return self.default
        channels = sample.shape[-3]
        for latent_space in self.alternates:
            if latent_space.channels == channels:
                return latent_space
        return self.default


def get_latent_space(base: BaseModelType) -> LatentSpace:
    """The latent space `base` denoises in; for the one architecture with several, its default.

    Use this where no sample is available yet -- to hoist the projection out of a per-step closure,
    for instance. Use `resolve_latent_space()` where there is a sample.
    """
    return require(base, LatentSpaceFacet).default


def resolve_latent_space(base: BaseModelType, sample: torch.Tensor) -> LatentSpace:
    """The latent space `base` denoises in, disambiguated by `sample` where it has more than one."""
    return require(base, LatentSpaceFacet).resolve(sample)
